def essay(seed):
    r = random.Random(seed)
    claim = r.choice(CLAIMS_PRO + CLAIMS_CON)
    lines = [claim]
    lines += r.sample(REASONS, k=r.choice([1, 2, 3]))
    obj = r.choice(OBJECTIONS)
    if obj:
        lines.append(obj)
    lines.append(r.choice(CLOSINGS))
    return "\n".join(lines)


def make_submissions(base: Path):
    folder = base / "04-submissions"
    roster = [["학번", "이름"]] + [[f"2026-{i:04d}", f"학생{i:02d}"] for i in range(1, 31)]
    write_csv(folder / "roster.csv", roster)

    sub = folder / "submissions"
    # 파일 이름 패턴 (제각각)
    patterns = [
        lambda i: f"2026-{i:04d}_과제1.txt",
        lambda i: f"학생{i:02d} 과제.txt",
        lambda i: f"과제1_학생{i:02d}.txt",
        lambda i: f"{i:04d}_assignment1.txt",
        lambda i: f"2026{i:04d} 학생{i:02d} 공리주의.txt",
        lambda i: f"과제1 제출 2026-{i:04d}.txt",
    ]
    nameless = {3: "과제1_최종(2).txt", 17: "공리주의 과제 최종.txt", 25: "제출합니다.txt"}
    on_time_times = {}
    t0 = dt.datetime(2026, 10, 18, 14, 0)
    rows = []
    for i in range(1, 31):
        if i in MISSING:
            continue
        if i in LATE:
            when = LATE[i]
        elif i in EDGE_ON_TIME:
            when = EDGE_ON_TIME[i]
        else:
            when_dt = t0 + dt.timedelta(minutes=rng.randint(0, 2 * 24 * 60 + 9 * 60))
            when = when_dt.strftime("%Y-%m-%d %H:%M")
        on_time_times[i] = when
        if i in nameless:
            fname = nameless[i]
        elif i == 21:
            fname = "학생11_과제1.txt"  # 이름 실수: 실제로는 학생21 (확인 필요)
        else:
            fname = patterns[i % len(patterns)](i)
        body = f"제출일시: {when}\n학번: 2026-{i:04d}\n이름: 학생{i:02d}\n\n{essay(i)}"
        write(sub / fname, body)
        rows.append((i, fname, when))
        if i == DOUBLE:
            when2 = "2026-10-20 23:40"
            fname2 = "2026-0014_과제1_수정본.txt"
            body2 = f"제출일시: {when2}\n학번: 2026-0014\n이름: 학생14\n\n(수정본) {essay(i + 100)}"
            write(sub / fname2, body2)
            rows.append((i, fname2, when2))
    return rows


